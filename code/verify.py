#!/usr/bin/env python3
"""Check that a fresh run reproduces the committed results.

Compares every numeric column in results/ against the committed copy and reports
the largest absolute deviation per file.

Exact byte-for-byte agreement is not the standard, and should not be expected:
the analysis involves floating-point reductions whose last digits depend on the
BLAS implementation and library versions. Reproducing the deposit on macOS with
Apple Accelerate, against a Linux/OpenBLAS reference, moves values by at most
about 1e-9 on quantities of order 1 — nine significant figures of agreement, far
below any precision the paper reports.

TOLERANCE below is set well above that noise floor and well below the third
decimal place, which is the finest precision any reported number uses.

Usage:  python code/verify.py
Exit:   0 = reproduced, 1 = a difference large enough to matter
"""

from __future__ import annotations

import io
import subprocess
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"
TOLERANCE = 1e-6

# Emitted during base-model fitting, not regenerated by this pipeline.
DEPOSITED = {"cell_split_boundaries.csv", "percell_validation_and_test_metrics.csv"}


def committed(rel: str) -> pd.DataFrame | None:
    r = subprocess.run(["git", "show", f"HEAD:{rel}"], cwd=ROOT,
                       capture_output=True, text=True)
    if r.returncode != 0:
        return None
    return pd.read_csv(io.StringIO(r.stdout))


def main() -> int:
    if not (ROOT / ".git").exists():
        print("Not a git checkout — nothing to compare against.", file=sys.stderr)
        return 1

    rows, worst, failed = [], 0.0, []
    for path in sorted(RESULTS.glob("*.csv")):
        if path.name in DEPOSITED:
            continue
        rel = f"results/{path.name}"
        old = committed(rel)
        if old is None:
            rows.append((path.name, "not in HEAD", ""))
            continue
        new = pd.read_csv(path)
        cols = [c for c in new.columns
                if c in old.columns and new[c].dtype.kind in "fi"
                and old[c].dtype.kind in "fi"]
        if not cols or new.shape[0] != old.shape[0]:
            rows.append((path.name, "shape/columns differ", "FAIL"))
            failed.append(path.name)
            continue
        d = np.abs(new[cols].to_numpy(float) - old[cols].to_numpy(float))
        m = float(np.nanmax(d)) if d.size else 0.0
        worst = max(worst, m)
        ok = m <= TOLERANCE
        if not ok:
            failed.append(path.name)
        rows.append((path.name, f"{m:.3e}", "ok" if ok else "FAIL"))

    width = max(len(r[0]) for r in rows) + 2
    print(f"{'file':<{width}}{'max |diff|':<16}")
    for name, val, flag in rows:
        print(f"{name:<{width}}{val:<16}{flag}")

    print(f"\ntolerance: {TOLERANCE:.0e}   largest deviation: {worst:.3e}")
    if failed:
        print("\nFAILED: " + ", ".join(failed))
        print("Differences this large are not floating-point noise. Check the "
              "environment and the package versions in requirements.txt.")
        return 1
    print("\nReproduced. All results agree with the deposit to well beyond the "
          "precision the paper reports.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
